"""Recreate the two experiment figures from saved JSONL data."""
from pathlib import Path
import json
import matplotlib.pyplot as plt


def main():
    root = Path(__file__).resolve().parents[1]
    out = root / "figures"
    out.mkdir(exist_ok=True)
    rows = [json.loads(line) for line in (root / "results/sweep_summary.jsonl").read_text().splitlines()]
    fig, ax = plt.subplots(figsize=(8.5, 4.8))
    for N in (2, 3, 4, 5, 6):
        data = sorted((r for r in rows if r["N"] == N and r["prime"] == 1000003), key=lambda r: r["k"])
        ax.plot([r["k"] for r in data], [r["defect"] for r in data], marker="o", label=f"N = {N}")
    ax.set_yscale("symlog", linthresh=1)
    ax.set_xlabel("Velocity degree k (potential degree = k + 1)")
    ax.set_ylabel("Modular nullity minus vertex-star span rank")
    ax.set_title("AIM 633: spanning deficits across the degree threshold")
    ax.legend()
    ax.grid(True, alpha=0.25)
    fig.tight_layout()
    fig.savefig(out / "spanning_deficits.png", dpi=180)
    plt.close(fig)

    rows = [json.loads(line) for line in (root / "results/degree_steps.jsonl").read_text().splitlines()]
    data = sorted((r for r in rows if r["N"] == 4 and r["coordinate"] == [2, 2, 2]), key=lambda r: r["high_potential_degree"])
    degrees = [r["high_potential_degree"] for r in data]
    deficits = [r["new_generator_defect"] for r in data]
    fig, ax = plt.subplots(figsize=(8.5, 4.8))
    ax.bar(degrees, deficits)
    for d, deficit in zip(degrees, deficits):
        ax.text(d, deficit + 1.5, str(deficit), ha="center")
    ax.set_xticks(degrees)
    ax.set_xlabel("Potential degree d")
    ax.set_ylabel("Dimension not generated by affine multiples of degree d − 1")
    ax.set_title("A genuine interior vertex star: new generators by degree")
    fig.tight_layout()
    fig.savefig(out / "interior_new_generators.png", dpi=180)
    plt.close(fig)


if __name__ == "__main__":
    main()
